import { createPortal } from 'react-dom';
import logo from 'figma:asset/5e73e3c08e898d68c86717993c6e7442d03e9ac4.png';
import { formatOperationalStamp } from '../../lib/assignmentOperational';
import './WeeklyPrintReport.css';

interface WeeklyPrintRow {
  date: string;
  asn: string;
  driver: string;
  truck: string;
  route: string;
  eta: string;
  ata: string;
  status: string;
}

interface Props {
  rows: WeeklyPrintRow[];
  summary: { total: number; completed: number; delayed: number; active: number };
  includedDeliveryDates: string[];
  generatedAt: Date;
  generatedBy: string;
  role: 'OPM' | 'CSR';
}

function deliveryDay(value: string): string | null {
  const parsed = new Date(value);
  if (!Number.isFinite(parsed.getTime())) return null;
  const iso = /^\d{4}-\d{2}-\d{2}$/.test(value.trim());
  const year = iso ? parsed.getUTCFullYear() : parsed.getFullYear();
  const month = (iso ? parsed.getUTCMonth() : parsed.getMonth()) + 1;
  const day = iso ? parsed.getUTCDate() : parsed.getDate();
  return `${year}-${String(month).padStart(2, '0')}-${String(day).padStart(2, '0')}`;
}

function includedDateSpan(values: string[]): string | null {
  const days = values.map(deliveryDay).filter((day): day is string => day !== null).sort();
  if (!days.length) return null;
  const label = (day: string) => new Intl.DateTimeFormat('en-US', {
    timeZone: 'UTC', month: 'short', day: 'numeric', year: 'numeric',
  }).format(new Date(`${day}T00:00:00Z`));
  return days[0] === days[days.length - 1] ? label(days[0]) : `${label(days[0])} – ${label(days[days.length - 1])}`;
}

export default function WeeklyPrintReport({ rows, summary, includedDeliveryDates, generatedAt, generatedBy, role }: Props) {
  const dateSpan = includedDateSpan(includedDeliveryDates);
  const generatedStamp = formatOperationalStamp(generatedAt.toISOString()) ?? generatedAt.toISOString();

  return createPortal(
    <article className="weekly-print-report" aria-label="Printable Weekly Performance Report">
      <header className="wpr-header">
        <div className="wpr-header-main">
          <img src={logo} alt="360 Logistics" className="wpr-logo" />
          <h1>Weekly Performance Report</h1>
          <p>Coverage: All included active and completed assignments</p>
          {dateSpan && <p>Included delivery dates: {dateSpan}</p>}
          <p>Generated on: {generatedStamp}</p>
        </div>
        <div className="wpr-verification">
          <strong>Verification unavailable</strong>
          <span>No report ID or verification record has been issued.</span>
        </div>
      </header>

      <section className="wpr-section">
        <h2>Weekly Summary</h2>
        <table className="wpr-summary">
          <thead><tr><th>Total Deliveries</th><th>Completed</th><th>Delayed</th><th>Active</th></tr></thead>
          <tbody><tr>
            <td>{summary.total}</td>
            <td className="wpr-completed">{summary.completed}</td>
            <td className={summary.delayed > 0 ? 'wpr-delayed' : ''}>{summary.delayed}</td>
            <td className="wpr-active">{summary.active}</td>
          </tr></tbody>
        </table>
      </section>

      <section className="wpr-section">
        <h2>Delivery Performance</h2>
        <table className="wpr-deliveries">
          <colgroup>
            <col className="wpr-col-date" /><col className="wpr-col-asn" />
            <col className="wpr-col-driver" /><col className="wpr-col-truck" />
            <col className="wpr-col-route" /><col className="wpr-col-eta" />
            <col className="wpr-col-ata" /><col className="wpr-col-status" />
          </colgroup>
          <thead><tr>
            <th>Date</th><th>ASN</th><th>Driver</th><th>Truck #</th>
            <th>Route</th><th>ETA</th><th>ATA</th><th>Status</th>
          </tr></thead>
          <tbody>
            {rows.length ? rows.map((row, index) => (
              <tr key={`${row.asn}-${index}`}>
                <td>{row.date}</td><td>{row.asn}</td><td>{row.driver}</td><td>{row.truck}</td>
                <td>{row.route}</td><td>{row.eta}</td><td>{row.ata}</td>
                <td className={row.status === 'Completed' ? 'wpr-completed' : row.status === 'Delayed' ? 'wpr-delayed' : ''}>{row.status}</td>
              </tr>
            )) : <tr><td colSpan={8}>No delivery records are included.</td></tr>}
          </tbody>
        </table>
      </section>

      <section className="wpr-section wpr-notes">
        <h2>Weekly Notes</h2>
        <dl>
          <div><dt>Completed deliveries</dt><dd>{summary.completed}</dd></div>
          <div><dt>Delayed deliveries</dt><dd>{summary.delayed}</dd></div>
          <div><dt>Active deliveries</dt><dd>{summary.active}</dd></div>
        </dl>
      </section>

      <footer className="wpr-audit">
        <strong>360 Logistics PH</strong>
        <span>Generated by: {generatedBy} · {role}</span>
        <span>Generated on: {generatedStamp}</span>
      </footer>
    </article>,
    document.body,
  );
}
