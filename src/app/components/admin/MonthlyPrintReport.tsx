import { createPortal } from 'react-dom';
import logo from 'figma:asset/5e73e3c08e898d68c86717993c6e7442d03e9ac4.png';
import { formatOperationalStamp } from '../../lib/assignmentOperational';
import ReportVerificationBox from './ReportVerificationBox';
import './WeeklyPrintReport.css';
import './MonthlyPrintReport.css';

interface MonthlyReportData {
  month: string;
  total: number;
  completed: number;
  onTime: number;
  delayed: number;
  cancelled: number;
  active: number;
  weeks: number[];
}

interface Props {
  month: MonthlyReportData;
  breakdownMonths: MonthlyReportData[];
  generatedAt: Date;
  generatedBy: string;
  role: 'OPM' | 'CSR';
  reportId: string | null;
  qrDataUrl: string | null;
}

export default function MonthlyPrintReport({ month, breakdownMonths, generatedAt, generatedBy, role, reportId, qrDataUrl }: Props) {
  const generatedStamp = formatOperationalStamp(generatedAt.toISOString()) ?? generatedAt.toISOString();
  const completionRate = month.total ? `${((month.completed / month.total) * 100).toFixed(1)}%` : '—';
  const onTimeRate = month.completed ? `${((month.onTime / month.completed) * 100).toFixed(1)}%` : '—';
  const busiestWeek = Math.max(...month.weeks, 0);

  return createPortal(
    <article className="weekly-print-report monthly-print-report" aria-label="Printable Monthly Delivery Summary">
      <header className="wpr-header">
        <div className="wpr-header-main">
          <img src={logo} alt="360 Logistics" className="wpr-logo" />
          <h1>Monthly Delivery Summary</h1>
          <p>Reporting month: {month.month}</p>
          <p>Generated on: {generatedStamp}</p>
        </div>
        <ReportVerificationBox reportId={reportId} qrDataUrl={qrDataUrl} />
      </header>

      <section className="wpr-section">
        <h2>Monthly Summary</h2>
        <table className="wpr-summary mds-summary">
          <thead><tr><th>Total Deliveries</th><th>Completed</th><th>Completion Rate</th><th>On-Time Rate</th></tr></thead>
          <tbody><tr>
            <td>{month.total}</td>
            <td className="wpr-completed">{month.completed}</td>
            <td>{completionRate}</td>
            <td className="wpr-completed">{onTimeRate}</td>
          </tr></tbody>
        </table>
        <table className="wpr-summary mds-summary mds-summary-secondary">
          <thead><tr><th>Delayed</th><th>Cancelled</th><th>Active</th></tr></thead>
          <tbody><tr>
            <td className={month.delayed > 0 ? 'wpr-delayed' : ''}>{month.delayed}</td>
            <td>{month.cancelled}</td>
            <td className="wpr-active">{month.active}</td>
          </tr></tbody>
        </table>
      </section>

      <section className="wpr-section mds-activity">
        <h2>Delivery Activity</h2>
        <p>Scheduled delivery volume by day-of-month week.</p>
        <table>
          <thead><tr><th>Week</th><th>Delivery volume</th><th>Count</th></tr></thead>
          <tbody>{month.weeks.map((count, index) => (
            <tr key={index}>
              <td>Week {index + 1}</td>
              <td><span className="mds-bar-track"><span className="mds-bar" style={{ width: `${busiestWeek ? (count / busiestWeek) * 100 : 0}%` }} /></span></td>
              <td>{count}</td>
            </tr>
          ))}</tbody>
        </table>
      </section>

      <section className="wpr-section mds-breakdown">
        <h2>Monthly Breakdown <span>All available reporting months</span></h2>
        <table>
          <thead><tr>
            <th>Month</th><th>Total</th><th>Completed</th><th>Active</th>
            <th>On-Time</th><th>Delayed</th><th>Cancelled</th><th>Completion Rate</th>
          </tr></thead>
          <tbody>{breakdownMonths.map((row) => (
            <tr key={row.month}>
              <td>{row.month}</td><td>{row.total}</td><td>{row.completed}</td><td>{row.active}</td>
              <td>{row.onTime}</td><td>{row.delayed}</td><td>{row.cancelled}</td>
              <td>{row.total ? `${((row.completed / row.total) * 100).toFixed(1)}%` : '—'}</td>
            </tr>
          ))}</tbody>
        </table>
      </section>

      <section className="wpr-section wpr-notes">
        <h2>Monthly Notes</h2>
        <dl>
          <div><dt>Completed deliveries</dt><dd>{month.completed}</dd></div>
          <div><dt>Active deliveries</dt><dd>{month.active}</dd></div>
          <div><dt>Delayed deliveries</dt><dd>{month.delayed}</dd></div>
          <div><dt>Cancelled deliveries</dt><dd>{month.cancelled}</dd></div>
          <div><dt>On-time rate</dt><dd>{onTimeRate}</dd></div>
        </dl>
      </section>

      <footer className="wpr-audit">
        <strong>360 Logistics PH</strong>
        <span>Generated by: {generatedBy}</span>
        <span>Role: {role}</span>
        <span>Generated on: {generatedStamp}</span>
        <span>Report ID: Not issued</span>
      </footer>
    </article>,
    document.body,
  );
}
