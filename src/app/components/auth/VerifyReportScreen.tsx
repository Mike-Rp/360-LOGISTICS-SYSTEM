import { useEffect, useState } from 'react';
import { CheckCircle2, XCircle, Loader2 } from 'lucide-react';
import imgLogo from 'figma:asset/5e73e3c08e898d68c86717993c6e7442d03e9ac4.png';
import { verifyReport, type VerifiedReport } from '../../lib/db';
import { REPORT_TYPE_LABEL } from '../../lib/reportTypes';

function fmtDate(iso: string | null): string {
  if (!iso) return '—';
  try { return new Date(iso).toLocaleDateString('en-US', { month: 'long', day: 'numeric', year: 'numeric' }); }
  catch { return iso; }
}
function fmtStamp(iso: string): string {
  try { return new Date(iso).toLocaleString('en-US', { month: 'long', day: 'numeric', year: 'numeric', hour: '2-digit', minute: '2-digit' }); }
  catch { return iso; }
}

/* Public verification page for a report's QR code / printed Report ID. No session
   required — verifyReport() is granted to anon and returns only safe metadata. */
export default function VerifyReportScreen() {
  const id = new URLSearchParams(window.location.search).get('id');
  const [report, setReport] = useState<VerifiedReport | null | undefined>(undefined);
  const [error, setError] = useState('');

  useEffect(() => {
    if (!id) { setReport(null); return; }
    let alive = true;
    verifyReport(id)
      .then((result) => { if (alive) setReport(result); })
      .catch(() => { if (alive) { setError('Could not check this report right now. Please try again.'); setReport(null); } });
    return () => { alive = false; };
  }, [id]);

  return <main className="min-h-dvh bg-gradient-to-br from-green-50 to-blue-50 px-4 py-8 flex items-center justify-center">
    <section className="w-full max-w-md rounded-2xl bg-white p-6 sm:p-8 shadow-xl" aria-labelledby="verify-title">
      <img src={imgLogo} alt="360 Logistics" className="mx-auto mb-6 h-16 w-auto max-w-full object-contain" />
      <h1 id="verify-title" className="text-2xl font-semibold text-center">Report Verification</h1>

      {report === undefined ? (
        <div className="mt-8 flex flex-col items-center gap-2 text-muted-foreground">
          <Loader2 className="h-6 w-6 animate-spin" />
          <p className="text-sm">Checking this report…</p>
        </div>
      ) : report ? (
        <div className="mt-6">
          <div className="flex items-center gap-2 rounded-xl border border-green-200 bg-green-50 px-4 py-3">
            <CheckCircle2 className="h-5 w-5 shrink-0 text-green-600" />
            <p className="text-sm font-semibold text-green-800">This is a genuine 360 Logistics report.</p>
          </div>
          <dl className="mt-5 space-y-3 text-sm">
            <div className="flex justify-between gap-3"><dt className="text-muted-foreground">Report ID</dt><dd className="font-mono font-semibold break-all text-right">{report.id}</dd></div>
            <div className="flex justify-between gap-3"><dt className="text-muted-foreground">Report type</dt><dd className="font-medium text-right">{REPORT_TYPE_LABEL[report.reportType] ?? report.reportType}</dd></div>
            {(report.periodStart || report.periodEnd) && (
              <div className="flex justify-between gap-3"><dt className="text-muted-foreground">Reporting period</dt><dd className="font-medium text-right">{fmtDate(report.periodStart)} – {fmtDate(report.periodEnd)}</dd></div>
            )}
            <div className="flex justify-between gap-3"><dt className="text-muted-foreground">Rows included</dt><dd className="font-medium text-right">{report.rowCount}</dd></div>
            <div className="flex justify-between gap-3"><dt className="text-muted-foreground">Generated by</dt><dd className="font-medium text-right">{report.generatedByName}</dd></div>
            <div className="flex justify-between gap-3"><dt className="text-muted-foreground">Generated on</dt><dd className="font-medium text-right">{fmtStamp(report.generatedAt)}</dd></div>
          </dl>
        </div>
      ) : (
        <div className="mt-6 flex items-start gap-2 rounded-xl border border-red-200 bg-red-50 px-4 py-3">
          <XCircle className="h-5 w-5 shrink-0 text-red-600" />
          <p className="text-sm text-red-800">
            {error || (id ? 'No report matches this ID. It may have been mistyped, or this is not a genuine 360 Logistics report.' : 'No report ID was given.')}
          </p>
        </div>
      )}
    </section>
  </main>;
}
