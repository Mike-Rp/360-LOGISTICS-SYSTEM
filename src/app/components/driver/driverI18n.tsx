const keyFor = (prefix: string, value: string) => `${prefix}.${value}` as TranslationKey;
const storageKey = (driverId: string) => `360logistics.driver.language.${driverId}`;
const lastLanguageKey = '360logistics.driver.language';

export function getLastDriverLanguage(): DriverLanguage {
  try { return localStorage.getItem(lastLanguageKey) === 'fil' ? 'fil' : 'en'; }
  catch { return 'en'; }
}

export function translateDriver(language: DriverLanguage, key: TranslationKey, params?: Record<string, string | number>) {
  const template = (language === 'fil' ? fil[key] : undefined) ?? en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(params?.[name] ?? `{${name}}`));
}

interface DriverI18n {
  language: DriverLanguage;
  setLanguage: (language: DriverLanguage) => void;
  t: (key: TranslationKey, params?: Record<string, string | number>) => string;
  status: (value: string) => string;
  document: (value: string) => string;
  reason: (value: string) => string;
}

const DriverI18nContext = createContext<DriverI18n | null>(null);

export function DriverLanguageProvider({ driverId, children }: { driverId: string; children: ReactNode }) {
  const [language, setCurrentLanguage] = useState<DriverLanguage>(() => {
    try { return localStorage.getItem(storageKey(driverId)) === 'fil' ? 'fil' : 'en'; }
    catch { return 'en'; }
  });
  const setLanguage = useCallback((next: DriverLanguage) => {
    setCurrentLanguage(next);
    try {
      localStorage.setItem(storageKey(driverId), next);
      localStorage.setItem(lastLanguageKey, next);
    } catch { /* Storage may be unavailable. */ }
  }, [driverId]);
  const t: DriverI18n['t'] = useCallback((key, params) => translateDriver(language, key, params), [language]);
  const value: DriverI18n = useMemo(() => ({
    language, setLanguage, t,
    status: (status) => t(keyFor('status', status)) === keyFor('status', status) ? status : t(keyFor('status', status)),
    document: (document) => t(keyFor('doc', document)) === keyFor('doc', document) ? document : t(keyFor('doc', document)),
    reason: (reason) => t(keyFor('reason', reason)) === keyFor('reason', reason) ? reason : t(keyFor('reason', reason)),
  }), [language, setLanguage, t]);
  return <DriverI18nContext.Provider value={value}>{children}</DriverI18nContext.Provider>;
}

export function useDriverI18n() {
  const context = useContext(DriverI18nContext);
  if (!context) throw new Error('Driver language provider is missing');
  return context;
}
