-- ════════════════════════════════════════════════════════════════════════════
-- OPM may issue reports — database tests
-- (run AFTER 20261105000002_opm_issue_reports.sql).
--
-- Leaves NOTHING behind: one transaction, one DO block that always finishes by
-- raising an exception, then ROLLBACK. Read the final message:
--   "OPM REPORT TESTS PASSED (n checks) — rolled back on purpose"  → all good
--   "OPM REPORT FAIL: …"                                            → what broke
--
-- Throwaway users only (@opmrpt-test.invalid); real rows are never touched
-- (the reports it issues are rolled back). Run the whole file at once.
-- ════════════════════════════════════════════════════════════════════════════
begin;

do $test$
declare
  n       int := 0;
  csr_u   uuid := gen_random_uuid();  csr_s  uuid := gen_random_uuid();
  adm_u   uuid := gen_random_uuid();  adm_s  uuid := gen_random_uuid();
  opm_u   uuid := gen_random_uuid();  opm_s  uuid := gen_random_uuid();  opm_old uuid := gen_random_uuid();
  rem_u   uuid := gen_random_uuid();  rem_s  uuid := gen_random_uuid();
  drv_u   uuid := gen_random_uuid();  drv_s  uuid := gen_random_uuid();
  c_csr text; c_adm text; c_opm text; c_opm_old text; c_rem text; c_drv text;
  exp_uid  uuid;
  exp_name text;
  who    text;
  t      text;
  res    jsonb;
  rid    text;
  r      public.issued_reports%rowtype;
  err    text;
  ok     boolean;
begin
  -- ── setup: CSR, admin, an active OPM, a REMOVED OPM, a driver (no staff profile) ──
  insert into auth.users (id, aud, role, email, created_at, updated_at)
  values (csr_u, 'authenticated', 'authenticated', 'csr@opmrpt-test.invalid', now(), now()),
         (adm_u, 'authenticated', 'authenticated', 'adm@opmrpt-test.invalid', now(), now()),
         (opm_u, 'authenticated', 'authenticated', 'opm@opmrpt-test.invalid', now(), now()),
         (rem_u, 'authenticated', 'authenticated', 'rem@opmrpt-test.invalid', now(), now()),
         (drv_u, 'authenticated', 'authenticated', 'drv@opmrpt-test.invalid', now(), now());
  insert into public.profiles (id, email, name, role, status)
  values (csr_u, 'csr@opmrpt-test.invalid', 'Opmrpt Test Csr', 'csr', 'active'),
         (adm_u, 'adm@opmrpt-test.invalid', 'Opmrpt Test Admin', 'admin', 'active'),
         (opm_u, 'opm@opmrpt-test.invalid', 'Opmrpt Test Opm', 'opm', 'active'),
         (rem_u, 'rem@opmrpt-test.invalid', 'Opmrpt Test Removed', 'opm', 'removed');
  insert into auth.sessions (id, user_id, created_at, updated_at) values
    (csr_s, csr_u, now(), now()), (adm_s, adm_u, now(), now()),
    (opm_old, opm_u, now() - interval '10 minutes', now()), (opm_s, opm_u, now(), now()),
    (rem_s, rem_u, now(), now()), (drv_s, drv_u, now(), now());
  c_csr     := jsonb_build_object('sub', csr_u, 'role', 'authenticated', 'session_id', csr_s)::text;
  c_adm     := jsonb_build_object('sub', adm_u, 'role', 'authenticated', 'session_id', adm_s)::text;
  c_opm     := jsonb_build_object('sub', opm_u, 'role', 'authenticated', 'session_id', opm_s)::text;
  c_opm_old := jsonb_build_object('sub', opm_u, 'role', 'authenticated', 'session_id', opm_old)::text;
  c_rem     := jsonb_build_object('sub', rem_u, 'role', 'authenticated', 'session_id', rem_s)::text;
  c_drv     := jsonb_build_object('sub', drv_u, 'role', 'authenticated', 'session_id', drv_s)::text;

  -- ── 1. grants unchanged: signed-in users may call it, anonymous may not ──
  if has_function_privilege('anon', 'public.issue_report(text,date,date,int,text)', 'EXECUTE')
     or not has_function_privilege('authenticated', 'public.issue_report(text,date,date,int,text)', 'EXECUTE') then
    raise exception 'OPM REPORT FAIL: wrong execute privileges on issue_report()';
  end if;
  n := n + 1;

  -- ── 2. an active OPM issues all four report types; the response shape is unchanged ──
  set local role authenticated;
  perform set_config('request.jwt.claims', c_opm, true);
  foreach t in array array['weekly', 'monthly', 'delay', 'utilization'] loop
    res := public.issue_report(t, date '2026-11-02', date '2026-11-08', 7, 'digest-' || t);
    rid := res ->> 'id';
    if rid !~ '^RPT-[0-9A-F]{12}$' or (select array_agg(k order by k) from jsonb_object_keys(res) k) is distinct from array['generatedAt', 'id'] then
      raise exception 'OPM REPORT FAIL: OPM issuing % gave %', t, res;
    end if;
    reset role;
    select * into r from public.issued_reports where id = rid;
    if not found or r.report_type <> t or r.row_count <> 7 or r.row_digest <> 'digest-' || t
       or r.report_period_start <> date '2026-11-02' or r.report_period_end <> date '2026-11-08' then
      raise exception 'OPM REPORT FAIL: stored % report is wrong: %', t, to_jsonb(r);
    end if;
    set local role authenticated;
    perform set_config('request.jwt.claims', c_opm, true);
  end loop;
  reset role;
  n := n + 1;

  -- ── 3. "Generated by" is the real signed-in OPM, taken from the database, and generated_at is the server's ──
  set local role authenticated;
  perform set_config('request.jwt.claims', c_opm, true);
  res := public.issue_report('weekly', null, null, 0, null);
  reset role;
  select * into r from public.issued_reports where id = res ->> 'id';
  if r.generated_by_user_id <> opm_u or r.generated_by_name <> 'Opmrpt Test Opm'
     or r.generated_at is null or abs(extract(epoch from (r.generated_at - now()))) > 5
     or r.report_period_start is not null or r.report_period_end is not null then
    raise exception 'OPM REPORT FAIL: generated-by / time stamping wrong: %', to_jsonb(r);
  end if;
  n := n + 1;

  -- ── 4. CSR and admin still can, each stamped with their own name ──
  foreach who in array array['csr', 'adm'] loop
    -- (computed here: an IF condition cannot contain CASE … THEN in PL/pgSQL)
    exp_uid  := case who when 'csr' then csr_u else adm_u end;
    exp_name := case who when 'csr' then 'Opmrpt Test Csr' else 'Opmrpt Test Admin' end;
    set local role authenticated;
    perform set_config('request.jwt.claims', case who when 'csr' then c_csr else c_adm end, true);
    foreach t in array array['weekly', 'monthly', 'delay', 'utilization'] loop
      res := public.issue_report(t, null, null, 1, null);
      reset role;
      select * into r from public.issued_reports where id = res ->> 'id';
      if r.report_type <> t or r.generated_by_user_id <> exp_uid or r.generated_by_name <> exp_name then
        raise exception 'OPM REPORT FAIL: % issuing % gave %', who, t, to_jsonb(r);
      end if;
      set local role authenticated;
      perform set_config('request.jwt.claims', case who when 'csr' then c_csr else c_adm end, true);
    end loop;
    reset role;
  end loop;
  n := n + 1;

  -- ── 5. still refused: anonymous, a driver, a removed OPM, a replaced OPM session, no session ──
  set local role anon;
  ok := false; begin perform public.issue_report('weekly', null, null, 1, null); exception when insufficient_privilege then ok := true; end;
  reset role;
  if not ok then raise exception 'OPM REPORT FAIL: anon could call issue_report()'; end if;
  set local role authenticated;
  foreach who in array array[c_drv, c_rem, c_opm_old, '{}'] loop
    perform set_config('request.jwt.claims', who, true);
    err := null; begin perform public.issue_report('weekly', null, null, 1, null); err := 'success'; exception when others then err := sqlerrm; end;
    if err is distinct from 'not_authorized' then raise exception 'OPM REPORT FAIL: an unauthorised caller got %', err; end if;
  end loop;
  reset role;
  n := n + 1;

  -- ── 6. validation is unchanged for OPM ──
  set local role authenticated;
  perform set_config('request.jwt.claims', c_opm, true);
  err := null; begin perform public.issue_report('yearly', null, null, 1, null); exception when others then err := sqlerrm; end;
  if err is distinct from 'invalid_report_type' then raise exception 'OPM REPORT FAIL: bad type gave %', coalesce(err, 'success'); end if;
  err := null; begin perform public.issue_report('weekly', null, null, -1, null); exception when others then err := sqlerrm; end;
  if err is distinct from 'invalid_row_count' then raise exception 'OPM REPORT FAIL: negative row count gave %', coalesce(err, 'success'); end if;
  reset role;
  n := n + 1;

  -- ── 7. OPM still cannot dispatch, edit, cancel or complete deliveries (can_write() was NOT widened) ──
  set local role authenticated;
  perform set_config('request.jwt.claims', c_opm, true);
  if public.can_write() or not public.is_opm() then
    raise exception 'OPM REPORT FAIL: can_write() / is_opm() are not as expected for OPM';
  end if;
  err := null; begin perform public.dispatch_assignment('{"driver_id":"x","truck_id":"y"}'::jsonb); exception when others then err := sqlerrm; end;
  if err is distinct from 'not_authorized' then raise exception 'OPM REPORT FAIL: OPM dispatch gave %', coalesce(err, 'success'); end if;
  err := null; begin perform public.edit_assignment('ASN-OPMRPT-NOPE', '{"remarks":"x"}', 'test'); exception when others then err := sqlerrm; end;
  if err is distinct from 'not_authorized' then raise exception 'OPM REPORT FAIL: OPM edit gave %', coalesce(err, 'success'); end if;
  err := null; begin perform public.cancel_assignment('ASN-OPMRPT-NOPE', 'a long enough reason', 'pw'); exception when others then err := sqlerrm; end;
  if err is distinct from 'not_authorized' then raise exception 'OPM REPORT FAIL: OPM cancel gave %', coalesce(err, 'success'); end if;
  err := null; begin perform public.complete_assignment('ASN-OPMRPT-NOPE'); exception when others then err := sqlerrm; end;
  if err is distinct from 'not_authorized' then raise exception 'OPM REPORT FAIL: OPM complete gave %', coalesce(err, 'success'); end if;
  reset role;
  n := n + 1;

  -- ── 8. the other report functions still behave: verify_report (public) and the staff listing ──
  set local role authenticated;
  perform set_config('request.jwt.claims', c_opm, true);
  res := public.issue_report('delay', null, null, 3, null);
  rid := res ->> 'id';
  reset role;
  set local role anon;
  if public.verify_report(rid) ->> 'generatedByName' <> 'Opmrpt Test Opm' or (public.verify_report(rid) ->> 'rowCount')::int <> 3
     or public.verify_report(rid) ? 'rowDigest' then
    raise exception 'OPM REPORT FAIL: verify_report() changed';
  end if;
  reset role;
  set local role authenticated;
  perform set_config('request.jwt.claims', c_opm, true);
  if (public.list_issued_reports_page(10, 0) -> 'reports' -> 0 ->> 'id') <> rid
     or (select count(*) from public.list_issued_reports(100)) <> least((public.list_issued_reports_page(10, 0) ->> 'total')::int, 100) then
    raise exception 'OPM REPORT FAIL: the report listing does not show the new report first';
  end if;
  reset role;
  n := n + 1;

  raise exception 'OPM REPORT TESTS PASSED (% checks) — rolled back on purpose, nothing was saved', n;
end
$test$;
rollback;
